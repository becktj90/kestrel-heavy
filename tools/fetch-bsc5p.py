#!/usr/bin/env python3
"""Regenerate data/astro/bsc5p-compact.csv from NASA HEASARC's BSC5P table (US Government work,
public domain per catalog.data.gov/dataset/bright-star-catalog). Keeps the 9000 brightest stars with
positions (High-tier cap), sorted by vmag then HR. Usage: python3 tools/fetch-bsc5p.py"""
import urllib.request, urllib.parse, re, base64, struct, math, os
q = urllib.parse.urlencode({'REQUEST': 'doQuery', 'LANG': 'ADQL', 'FORMAT': 'votable',
                            'QUERY': 'select hr,ra,dec,vmag,bv_color from bsc5p'})
s = urllib.request.urlopen('https://heasarc.gsfc.nasa.gov/xamin/vo/tap/sync?' + q).read().decode()
b = base64.b64decode(re.search(r'<STREAM encoding="base64">(.*?)</STREAM>', s, re.S).group(1))
rows = [struct.unpack('>hddff', b[i:i + 26]) for i in range(0, len(b), 26)]  # short, double, double, float, float
good = sorted((r for r in rows if r[0] != -32768 and not any(math.isnan(x) for x in r[1:4])), key=lambda r: (r[3], r[0]))[:9000]
out = os.path.join(os.path.dirname(__file__), '..', 'data', 'astro', 'bsc5p-compact.csv')
with open(out, 'w') as f:
    f.write("# Bright Star Catalogue, 5th Revised Ed. (Preliminary), Hoffleit & Warren 1991, via NASA HEASARC table BSC5P.\n"
            "# US Government work, public domain (see /LICENSES.md). Generated by tools/fetch-bsc5p.py\n"
            "# 9000 brightest stars with positions. id=HR number, raDeg/decDeg J2000, vmag, bv (blank=unknown)\n# id,raDeg,decDeg,vmag,bv\n")
    for h, ra, de, v, bv in good:
        f.write(f"{h},{ra:.5f},{de:.5f},{v:.2f},{'' if math.isnan(bv) else f'{bv:.2f}'}\n")
