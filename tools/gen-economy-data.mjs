// Regenerates web/js/economy-data/constants.js from constants.json (the source of truth).
// The browser loads the .js mirror (no JSON import attributes needed in WKWebView).
// tests/economy-data.test.cjs fails if the two drift.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../web/js/economy-data/', import.meta.url);
const data = JSON.parse(readFileSync(new URL('constants.json', dir), 'utf8'));
delete data.$schema;
writeFileSync(new URL('constants.js', dir), `// GENERATED by tools/gen-economy-data.mjs from constants.json. Do not edit by hand.\nexport const ECON = Object.freeze(${JSON.stringify(data, null, 2)});\nexport default ECON;\n`);
console.log('economy-data/constants.js written');
