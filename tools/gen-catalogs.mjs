// Regenerates web/js/data/gen/*.js from data/*.json (the source of truth for catalogs).
// The browser / WKWebView loads the .js mirrors (no JSON import attributes needed, and
// `npm run pack:ios` copies web/ as before). tests/catalogs-json.test.cjs fails on drift.
// Usage: node tools/gen-catalogs.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
export const CATALOGS = ['propellants', 'engines', 'materials', 'payloads', 'presets', 'tanks', 'fairings', 'interstages', 'fins', 'codex'];
const root = new URL('../', import.meta.url);
export function render(name) {
  const data = JSON.parse(readFileSync(new URL(`data/${name}.json`, root), 'utf8'));
  delete data.$schema;
  return `// GENERATED by tools/gen-catalogs.mjs from data/${name}.json. Do not edit by hand.\nexport default ${JSON.stringify(data, null, 2)};\n`;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(new URL('web/js/data/gen/', root), { recursive: true });
  for (const n of CATALOGS) writeFileSync(new URL(`web/js/data/gen/${n}.js`, root), render(n));
  console.log(`web/js/data/gen/{${CATALOGS.join(',')}}.js written`);
}
