#!/usr/bin/env node
// Template pipeline. JSON in web/js/data/templates/*.json is the source of truth.
//   npm run templates:build   # recompute stats into each JSON, regenerate index.js
//   npm run templates:check   # exit 1 if stats/index.js are stale or a template misses its objective
// index.js exists because WKWebView on iOS 17.0 cannot import JSON modules.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { evaluateTemplate } from './evaluate.mjs';

const DIR = join(dirname(fileURLToPath(import.meta.url)), '../../web/js/data/templates');
const check = process.argv.includes('--check');
const files = readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();
const list = [];
let bad = 0, stale = 0;
for (const f of files) {
  const raw = readFileSync(join(DIR, f), 'utf8');
  const t = JSON.parse(raw);
  const r = evaluateTemplate(t);
  const errs = [...r.schema, ...r.meta];
  if (errs.length || !r.pass) { bad++; console.error(`✗ ${t.id}: ${errs.join('; ') || r.why}`); }
  else console.log(`✓ ${t.id}: ${r.why}`);
  t.template.stats = r.stats;
  const out = JSON.stringify(t, null, 2) + '\n';
  if (out !== raw) { stale++; if (!check) writeFileSync(join(DIR, f), out); }
  list.push(t);
}
list.sort((a, b) => a.template.order - b.template.order);
const js = `// GENERATED by tools/templates/build.mjs from ./*.json. Do not edit; edit the JSON and rebuild.\n` +
  `export const TEMPLATES = Object.freeze(${JSON.stringify(list, null, 1)});\n` +
  `export const TEMPLATE_BY_ID = Object.freeze(Object.fromEntries(TEMPLATES.map((t) => [t.id, t])));\n`;
const idx = join(DIR, 'index.js');
let prev = ''; try { prev = readFileSync(idx, 'utf8'); } catch (_) { /* first run */ }
if (prev !== js) { stale++; if (!check) writeFileSync(idx, js); }
if (check && stale) console.error(`✗ ${stale} template file(s) stale: run npm run templates:build`);
process.exit(bad || (check && stale) ? 1 : 0);
