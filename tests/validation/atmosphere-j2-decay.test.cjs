// Validation (S2/S3): web/js/physics/atmosphere.js vs U.S. Standard Atmosphere 1976 tables,
// plus J2 precession and orbital decay status. Run: node --test tests/validation/
//
// Reference: U.S. Standard Atmosphere, 1976 (NOAA-S/T 76-1562, NOAA/NASA/USAF), Table I, geometric
// altitude, 5 significant figures. US Government work, public domain. Logged in LICENSES.md.
//
// Epsilons (relative, |model/table - 1|):
//   0-79 km  T, p, rho: 1e-4. The table is printed to 5 significant figures, so rounding alone is up to
//            5e-5 (e.g. 1.0524 Pa). The rest is headroom for R_AIR = 287.053 vs R*/M0 = 287.0531. Measured worst 6.7e-5.
//   80-86 km T: 5e-4. The table lists kinetic T. The code (like the USSA76 layer equations) uses
//            molecular-scale temperature T_M = T*M0/M; M/M0 = 0.99960 at 86 km gives a 4.0e-4 offset by design.
//            p, rho stay at 1e-4.
//   86-1000 km p, rho, T, sound speed: 1e-4 at the 5 km USSA76 Table I knots (z = 90, 95, ... 1000 km).
//            Same reasoning as below 86 km: the table is 5 significant figures (rounding up to 5e-5), and the
//            model stores those knots, so the measured error at a knot is ~1e-15. Anything above 1e-4 means a
//            transcription, indexing or units bug. Between knots ln(p), ln(rho) are linear: measured offline
//            against the full USSA76 equations at 250 m steps, the worst case is 2.5% (rho) at 112.5 km,
//            where T bends from 240 K to 300 K, and at most 0.3% above 150 km. That bound is documented here
//            and in docs/ACCURACY_REVIEW.md; it is not asserted, because the table has no values between knots.
//            Before this fix the isothermal 5.8 km tail was +11% at 100 km and off by orders of magnitude above 120 km.
//   >1000 km: extrapolated with the 995-1000 km scale height. Not validated (USSA76 stops at 1000 km).
//   No F10.7/Ap: USSA76 is one mean solar condition. Solar-cycle density (NRLMSIS-class) is a separate item.
