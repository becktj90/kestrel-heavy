// Readable timeline for review. Produced by the generator, not written by hand.
using System.Text;

namespace Kestrel.Core.Timeline
{
    public static class TimelineText
    {
        public static string Markdown(Timeline t)
        {
            var sb = new StringBuilder(4096);
            sb.Append("# ").Append(t.vehicleId).Append('\n');
            sb.Append('\n');
            sb.Append("Generated by `Kestrel.Core.Timeline.TimelineGenerator`. ");
            sb.Append("Mode ").Append(t.mode);
            sb.Append(", seed ").Append(t.seed);
            sb.Append(", pad `").Append(t.padId).Append('`');
            sb.Append(", recovery `").Append(t.recovery).Append('`');
            sb.Append(", latitude ").Append(TimelineJson.F(t.latitude)).Append("°.\n");
            sb.Append('\n');
            sb.Append("Nominal times are game seconds. T- is compressed for this mode (engineer keeps real seconds). ");
            sb.Append("T+ ascent times come from the headless sim. Actual is filled when the sim measured the event.\n");
            sb.Append('\n');
            sb.Append("## Sequence\n\n");
            sb.Append("| Game time | Actual | Id | Phase | Label | Why |\n");
            sb.Append("| --- | --- | --- | --- | --- | --- |\n");
            if (t.events != null)
            {
                foreach (var e in t.events)
                {
                    sb.Append("| ").Append(TimelineClock.Clock(e.nominal));
                    sb.Append(" | ").Append(e.actual.HasValue ? TimelineClock.Clock(e.actual.Value) : "—");
                    sb.Append(" | `").Append(e.id).Append('`');
                    sb.Append(" | ").Append(e.phase);
                    sb.Append(" | ").Append(Cell(e.strings?.shortLabel));
                    sb.Append(" | ").Append(Cell(e.strings?.explainWhy));
                    sb.Append(" |\n");
                }
            }
            sb.Append('\n');
            sb.Append("## Branches\n\n");
            if (t.branches == null || t.branches.Count == 0) sb.Append("None.\n");
            else
            {
                foreach (var e in t.branches)
                {
                    sb.Append("- `").Append(e.id).Append("` (").Append(e.phase).Append(") — ");
                    sb.Append(e.strings?.explainWhy ?? "").Append('\n');
                }
            }
            sb.Append('\n');
            sb.Append("## Absent\n\n");
            if (t.absent == null || t.absent.Count == 0) sb.Append("None.\n");
            else
            {
                foreach (var a in t.absent)
                    sb.Append("- `").Append(a.id).Append("` — ").Append(a.explainWhy).Append('\n');
            }
            sb.Append('\n');
            return sb.ToString();
        }

        static string Cell(string s)
        {
            if (string.IsNullOrEmpty(s)) return "";
            return s.Replace("|", "/").Replace("\n", " ");
        }
    }
}
