"""Writes Shell/MainMenu/MainMenuMetrics.cs: string widths at 100 px (advance + tracking) for the shipped subset fonts,
so EditMode tests and the layout maths can check fit without a font engine. Run after make_fonts.py."""
import sys
from fontTools.ttLib import TTFont
D = sys.argv[1]; OUT = sys.argv[2]
FONTS = {k: TTFont(f"{D}/{v}.ttf") for k, v in dict(FB="Fraunces-Black", FBo="Fraunces-Bold", GB="SpaceGrotesk-Bold", GM="SpaceGrotesk-Medium").items()}
def w(font, text, track_em):
    f = FONTS[font]; cm = f.getBestCmap(); hm = f["hmtx"]; upm = f["head"].unitsPerEm
    return sum(hm[cm[ord(c)]][0] for c in text) / upm * 100 + track_em * 100 * len(text)
import re
src = open(sys.argv[3]).read()
cap = lambda n: re.search(r'"(%s)"' % n, src)
rows = [
 ("KESTREL", "FB", .04), ("HEAVY", "GB", .5), ("LAUNCH", "FB", .10),
 ("Opens the pad. Build, then launch.", "GM", 0),
 ("HANGAR", "FBo", .03), ("MISSIONS", "FBo", .03), ("CODEX", "FBo", .03), ("SETTINGS", "FBo", .03),
 ("Design and tune your rocket.", "GM", 0), ("Pick any flight you've unlocked.", "GM", 0),
 ("Parts, places and flight notes.", "GM", 0), ("Sound, motion, accessibility.", "GM", 0),
 ("SOON", "GB", .15),
 ("TAP A TILE OR LAUNCH TO BEGIN", "GB", .18),
]
lines = ["// GENERATED by Art/Fonts/Tools~/make_metrics.py from the shipped subset fonts. Do not edit.",
 "// Width of each menu string at 100 px, including tracking, so layout and tests need no font engine.",
 "using System.Collections.Generic;", "", "namespace Kestrel.Game.Shell", "{", "    public static class MainMenuMetrics", "    {",
 "        public static readonly Dictionary<string, float> Width100 = new Dictionary<string, float>", "        {"]
for t, f, tr in rows:
    lines.append('            { "%s", %.2ff },' % (t.replace('\\', '\\\\').replace('"', '\\"').replace('\u00b7', '\\u00B7'), w(f, t, tr)))
lines += ["        };", "        public static float W(string s) => Width100[s];", "    }", "}"]
open(OUT, "w").write("\n".join(lines) + "\n")
