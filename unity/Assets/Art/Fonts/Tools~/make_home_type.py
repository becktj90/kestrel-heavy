"""Writes Kestrel.Core/Flight/HomeTypeMetrics.cs: per-character advances at 100 px for the four shipped
menu subset fonts, so the engine-free phone Home layout (HomePhoneLayout) can measure and word-wrap any
string (the record line, the credits chip, Thrum's line) without a font engine.
Usage: python3 make_home_type.py <fonts dir> <out .cs>"""
import sys
from fontTools.ttLib import TTFont
D, OUT = sys.argv[1], sys.argv[2]
FACES = [("FrauncesBlack", "Fraunces-Black"), ("FrauncesBold", "Fraunces-Bold"),
         ("GroteskBold", "SpaceGrotesk-Bold"), ("GroteskMedium", "SpaceGrotesk-Medium")]
CHARS = [chr(c) for c in range(32, 127)] + ["\u00b7", "\u2013", "\u2014", "\u2019"]
out = ["// GENERATED by Art/Fonts/Tools~/make_home_type.py from the shipped subset fonts. Do not edit.",
       "// Advance of each character at 100 px, no tracking. Index = HomeTypeMetrics.Index(c).",
       "namespace Kestrel.Core.Flight", "{", "    public static partial class HomeTypeMetrics", "    {"]
for name, file in FACES:
    f = TTFont(f"{D}/{file}.ttf"); cm = f.getBestCmap(); hm = f["hmtx"]; upm = f["head"].unitsPerEm
    vals = []
    for ch in CHARS:
        g = cm.get(ord(ch))
        vals.append(hm[g][0] / upm * 100 if g is not None else 0.0)
    rows = ", ".join("%.2ff" % v for v in vals)
    out.append("        static readonly float[] %s = { %s };" % (name, rows))
out += ["    }", "}"]
open(OUT, "w").write("\n".join(out) + "\n")
